#!/usr/bin/env bash
# Idempotent install of the local pi-H3 runtime: ComfyUI (pinned) + ComfyUI-piFlow (pinned) in a uv venv.
# Run inside WSL:  bash scripts/setup.sh        (re-running is safe; it only fills in what is missing)
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/_env.sh"

command -v uv >/dev/null || { h3_log "uv not found: curl -LsSf https://astral.sh/uv/install.sh | sh"; exit 1; }
command -v git >/dev/null || { h3_log "git not found"; exit 1; }
nvidia-smi >/dev/null || { h3_log "nvidia-smi failed: the GPU is not visible in this WSL distro"; exit 1; }

mkdir -p "$H3_RUNTIME" "$H3_MODELS"/{diffusion_models,text_encoders,vae,loras}

# 1. ComfyUI at a pinned tag
if [ ! -d "$H3_COMFY_DIR/.git" ]; then
  h3_log "cloning ComfyUI $COMFY_REF"
  git clone --quiet "$COMFY_REPO" "$H3_COMFY_DIR"
fi
git -C "$H3_COMFY_DIR" fetch --quiet --tags origin
git -C "$H3_COMFY_DIR" -c advice.detachedHead=false checkout --quiet "$COMFY_REF"

# 2. venv + PyTorch (CUDA 13 wheels; Blackwell sm_120 needs cu128+) + ComfyUI requirements
if [ ! -x "$H3_VENV/bin/python" ]; then
  h3_log "creating venv (python $PYTHON_VERSION)"
  uv venv --quiet --python "$PYTHON_VERSION" --managed-python "$H3_VENV"
fi
export VIRTUAL_ENV="$H3_VENV"
if ! "$H3_VENV/bin/python" -c 'import torch' 2>/dev/null; then
  h3_log "installing torch from $TORCH_INDEX"
  uv pip install --quiet torch torchvision torchaudio --index-url "$TORCH_INDEX"
fi
h3_log "installing ComfyUI requirements"
uv pip install --quiet -r "$H3_COMFY_DIR/requirements.txt" --extra-index-url "$TORCH_INDEX" --index-strategy unsafe-best-match

# 3. ComfyUI-piFlow custom nodes (pi-H3 adapter loader, pi-Flow scheduler, DWD Decode)
PIFLOW_DIR="$H3_COMFY_DIR/custom_nodes/ComfyUI-piFlow"
if [ ! -d "$PIFLOW_DIR/.git" ]; then
  h3_log "cloning ComfyUI-piFlow"
  git clone --quiet "$PIFLOW_REPO" "$PIFLOW_DIR"
fi
git -C "$PIFLOW_DIR" fetch --quiet origin
git -C "$PIFLOW_DIR" -c advice.detachedHead=false checkout --quiet "$PIFLOW_REF"
if [ -f "$PIFLOW_DIR/requirements.txt" ]; then
  uv pip install --quiet -r "$PIFLOW_DIR/requirements.txt"
fi

# 4. Model search paths: our own download folder first, then the optional shared folder
{
  echo "# Generated by scripts/setup.sh. Do not edit; change config/h3gen.env and re-run setup."
  echo "h3gen:"
  echo "  base_path: $H3_MODELS"
  echo "  diffusion_models: diffusion_models"
  echo "  text_encoders: text_encoders"
  echo "  vae: vae"
  echo "  loras: loras"
  if [ -n "$H3_SHARED_MODELS" ] && [ -d "$H3_SHARED_MODELS" ]; then
    echo "h3shared:"
    echo "  base_path: $H3_SHARED_MODELS"
    echo "  diffusion_models: diffusion_models"
    echo "  text_encoders: text_encoders"
    echo "  vae: vae"
    echo "  loras: loras"
  fi
} > "$H3_COMFY_DIR/extra_model_paths.yaml"

# 5. Record what got installed (agents: diff this file to see what changed between setups)
"$H3_VENV/bin/python" - <<'PY' > "$H3_RUNTIME/versions.txt"
import importlib.metadata as md, platform, torch
print('python', platform.python_version())
print('torch', torch.__version__, 'cuda', torch.version.cuda, 'cuda_available', torch.cuda.is_available())
if torch.cuda.is_available():
    print('gpu', torch.cuda.get_device_name(0), 'sm_%d%d' % torch.cuda.get_device_capability(0))
for p in ('comfyui-frontend-package', 'av', 'numpy', 'safetensors', 'triton'):
    try: print(p, md.version(p))
    except md.PackageNotFoundError: print(p, '-')
PY
echo "comfyui $(git -C "$H3_COMFY_DIR" describe --tags --always)" >> "$H3_RUNTIME/versions.txt"
echo "comfyui-piflow $(git -C "$PIFLOW_DIR" rev-parse --short HEAD)" >> "$H3_RUNTIME/versions.txt"
cat "$H3_RUNTIME/versions.txt"
h3_log "setup done. Next: bash scripts/download_models.sh"
